// Writes plugin/Source/dsp/Params.gen.h from src/dsp/params.ts: the flat
// parameter list, each unit's parameter ids, the bodies' and the field's
// constant tables and the factory presets, so the C++ engine and the host
// see exactly what the web version sees. Run after changing params.ts:
//
//   node scripts/gen-plugin.ts

import { writeFileSync } from 'node:fs';
import { PARAMS, PRESETS, BODIES, TUBES, ROLL_BEATS, UNITS, UNIT_PREFIX } from '../src/dsp/params.ts';
import { MEMBRANE, BELL, BAR, BODY_CONTACT, BODY_GAIN } from '../src/dsp/modal.ts';
import { TERRAIN_TAPS, TERRAIN_TAIL_SCALE, TAIL_BASE } from '../src/dsp/space.ts';

const out = 'plugin/Source/dsp/Params.gen.h';
const idx = new Map(PARAMS.map((p, i) => [p.id, i]));
const num = (x: number) => {
  const s = String(x);
  return /[.e]/.test(s) ? s : `${s}.0`;
};
const list = (xs: number[]) => xs.map(num).join(', ');
const str = (s: string | undefined) => (s === undefined ? 'nullptr' : JSON.stringify(s));
const SCALE = { lin: 'Lin', log: 'Log', int: 'Int', enum: 'Enum', bool: 'Bool' } as const;
// a unit's parameters, by the suffix after u1…u8
const UNIT_KEYS = ['Body', 'Level', 'Size', 'Tension', 'Damp', 'Char', 'Hard', 'Pos', 'Grit', 'Bend', 'Partial', 'Snap', 'Lip', 'Breath', 'Growl',
  'Count', 'Spread', 'Cohesion', 'Vary', 'Dist', 'Az', 'KeyLo', 'KeyHi', 'Track', 'Root', 'Roll', 'Accent'];
const field = (k: string) => (k === 'Char' ? 'chr' : k[0].toLowerCase() + k.slice(1));   // char is a C++ keyword

const L: string[] = [];
L.push('// Generated by scripts/gen-plugin.ts from src/dsp/params.ts. Do not edit.');
L.push('#pragma once');
L.push('');
L.push('namespace ftsiege {');
L.push('');
L.push('enum class Scale { Lin, Log, Int, Enum, Bool };');
L.push('');
L.push('struct ParamDef {');
L.push('  const char* id; const char* name; const char* group;');
L.push('  double min, max, def; Scale scale; const char* unit;');
L.push('  const char* const* labels; int numLabels;');
L.push('};');
L.push('');
L.push('namespace P {');
L.push('enum : int {');
for (const p of PARAMS) L.push(`  ${p.id},`);
L.push('  COUNT');
L.push('};');
L.push('}');
L.push('');
L.push('constexpr int NUM_PARAMS = P::COUNT;');
L.push('');
PARAMS.forEach((p) => {
  if (p.labels) L.push(`inline constexpr const char* LABELS_${p.id}[] = { ${p.labels.map((l) => JSON.stringify(l)).join(', ')} };`);
});
L.push('');
L.push('inline constexpr ParamDef PARAMS[NUM_PARAMS] = {');
for (const p of PARAMS) {
  const labels = p.labels ? `LABELS_${p.id}, ${p.labels.length}` : 'nullptr, 0';
  L.push(`  { ${str(p.id)}, ${str(p.name)}, ${str(p.group)}, ${num(p.min)}, ${num(p.max)}, ${num(p.def)}, Scale::${SCALE[p.scale]}, ${str(p.unit)}, ${labels} },`);
}
L.push('};');
L.push('');
L.push(`constexpr int UNITS = ${UNITS};`);
L.push('/** Per unit, the index of each of its parameters. */');
L.push(`struct UnitIds { int ${UNIT_KEYS.map(field).join(', ')}; };`);
L.push('inline constexpr UnitIds UNIT_IDS[UNITS] = {');
for (const pre of UNIT_PREFIX) {
  for (const k of UNIT_KEYS) if (!idx.has(`${pre}${k}`)) throw new Error(`no param ${pre}${k}`);
  L.push(`  { ${UNIT_KEYS.map((k) => `P::${pre}${k}`).join(', ')} },`);
}
L.push('};');
L.push('');
L.push('// ---- bodies (params.ts, modal.ts)');
L.push(`constexpr int NUM_BODIES = ${BODIES.length};`);
L.push(`enum : int { ${BODIES.map((b, i) => `BODY_${b.toUpperCase()} = ${i}`).join(', ')} };`);
L.push(`inline constexpr bool IS_TUBE[NUM_BODIES] = { ${BODIES.map((_, i) => (TUBES.includes(i) ? 'true' : 'false')).join(', ')} };`);
L.push(`inline constexpr double BODY_CONTACT[NUM_BODIES] = { ${list(BODY_CONTACT)} };`);
L.push(`inline constexpr double BODY_GAIN[NUM_BODIES] = { ${list(BODY_GAIN)} };`);
L.push(`constexpr int NUM_MEMBRANE = ${MEMBRANE.length};`);
L.push(`inline constexpr double MEMBRANE_RATIO[NUM_MEMBRANE] = { ${list(MEMBRANE.map((m) => m[0]))} };`);
L.push(`inline constexpr int MEMBRANE_M[NUM_MEMBRANE] = { ${MEMBRANE.map((m) => m[1]).join(', ')} };`);
L.push(`constexpr int NUM_BELL = ${BELL.length};`);
L.push(`inline constexpr double BELL[NUM_BELL] = { ${list(BELL)} };`);
L.push(`constexpr int NUM_BAR = ${BAR.length};`);
L.push(`inline constexpr double BAR[NUM_BAR] = { ${list(BAR)} };`);
L.push('');
L.push('// ---- the march (params.ts)');
L.push(`constexpr int NUM_ROLLS = ${ROLL_BEATS.length};`);
L.push(`inline constexpr double ROLL_BEATS[NUM_ROLLS] = { ${list(ROLL_BEATS)} };`);
L.push('');
L.push('// ---- the field (space.ts)');
L.push('struct Tap { double ms, g, bright, side; };');
const maxTaps = Math.max(...TERRAIN_TAPS.map((t) => t.length));
L.push(`constexpr int NUM_TERRAINS = ${TERRAIN_TAPS.length};`);
L.push(`constexpr int MAX_TAPS = ${maxTaps};`);
L.push(`inline constexpr int TERRAIN_NUM_TAPS[NUM_TERRAINS] = { ${TERRAIN_TAPS.map((t) => t.length).join(', ')} };`);
L.push('inline constexpr Tap TERRAIN_TAPS[NUM_TERRAINS][MAX_TAPS] = {');
for (const taps of TERRAIN_TAPS) {
  const cells = taps.map((t) => `{ ${num(t.ms)}, ${num(t.g)}, ${num(t.bright)}, ${num(t.side)} }`);
  while (cells.length < maxTaps) cells.push('{ 0.0, 0.0, 0.0, 0.0 }');
  L.push(`  { ${cells.join(', ')} },`);
}
L.push('};');
L.push(`inline constexpr double TERRAIN_TAIL_SCALE[NUM_TERRAINS] = { ${list(TERRAIN_TAIL_SCALE)} };`);
L.push(`constexpr int TAIL_LINES = ${TAIL_BASE.length};`);
L.push(`inline constexpr double TAIL_BASE[TAIL_LINES] = { ${list(TAIL_BASE)} };`);
L.push('');
L.push('struct PresetValue { int id; double value; };');
L.push('struct Preset { const char* name; const char* tag; const PresetValue* values; int count; };');
L.push('');
PRESETS.forEach((pr, i) => {
  const vals = Object.entries(pr.values).map(([id, v]) => {
    if (!idx.has(id)) throw new Error(`preset "${pr.name}": unknown param ${id}`);
    return `{ P::${id}, ${num(v!)} }`;
  });
  // an empty preset (init) has no array: C++ has no zero-length ones
  if (vals.length) L.push(`inline constexpr PresetValue PRESET_${i}[] = { ${vals.join(', ')} };`);
});
L.push('');
L.push(`constexpr int NUM_PRESETS = ${PRESETS.length};`);
L.push('inline constexpr Preset PRESETS[NUM_PRESETS] = {');
PRESETS.forEach((pr, i) => L.push(`  { ${str(pr.name)}, ${str(pr.tag)}, ${Object.keys(pr.values).length ? `PRESET_${i}` : 'nullptr'}, ${Object.keys(pr.values).length} },`));
L.push('};');
L.push('');
L.push('} // namespace ftsiege');
L.push('');

writeFileSync(out, L.join('\n'));
console.log(`wrote ${out}: ${PARAMS.length} params, ${PRESETS.length} presets`);
